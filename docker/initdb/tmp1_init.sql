-- BẢN TẠM
-- Chưa phải migration chính thức: tên constraint và index @Quyền
-- Chạy một lần khi volume PostgreSQL còn trống, bằng POSTGRES_USER
CREATE TYPE account_role AS ENUM ('STUDENT', 'ADMIN');
CREATE TYPE registration_status AS ENUM ('OPEN', 'CLOSED');
CREATE TYPE enrollment_status AS ENUM ('ENROLLED', 'FAILED');

CREATE TABLE account (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(20) NOT NULL UNIQUE,
    full_name varchar(100) NOT NULL,
    password_hash varchar(100) NOT NULL,
    role account_role NOT NULL
);
CREATE TABLE course (
    code varchar(12) PRIMARY KEY,
    name varchar(150) NOT NULL,
    credits smallint NOT NULL CHECK (credits BETWEEN 1 AND 10),
    prerequisite varchar(100) NOT NULL DEFAULT ''
);
CREATE TABLE registration_period (
    term varchar(10) PRIMARY KEY,
    login_opens_at timestamptz NOT NULL,
    opens_at timestamptz NOT NULL,
    closes_at timestamptz NOT NULL,
    status registration_status NOT NULL,
    credit_limit smallint NOT NULL CHECK (credit_limit > 0),
    CHECK (login_opens_at <= opens_at AND opens_at < closes_at)
);
CREATE UNIQUE INDEX one_open_period ON registration_period ((status)) WHERE status = 'OPEN';
CREATE TABLE section (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_code varchar(12) NOT NULL REFERENCES course(code),
    term varchar(10) NOT NULL REFERENCES registration_period(term),
    lecturer varchar(100) NOT NULL,
    capacity smallint NOT NULL CHECK (capacity > 0),
    enrolled_count smallint NOT NULL DEFAULT 0 CHECK (enrolled_count BETWEEN 0 AND capacity),
    session integer NOT NULL CHECK (session > 0 AND session < 268435456)
);
CREATE INDEX section_term_course_idx ON section (term, course_code);
CREATE TABLE enrollment (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id bigint NOT NULL REFERENCES account(id),
    section_id bigint NOT NULL REFERENCES section(id),
    status enrollment_status NOT NULL,
    fail_code varchar(30),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (student_id, section_id),
    CHECK (status <> 'FAILED' OR fail_code IS NOT NULL)
);
CREATE TABLE idempotency_record (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id bigint NOT NULL REFERENCES account(id),
    idempotency_key varchar(128) NOT NULL CHECK (length(idempotency_key) BETWEEN 1 AND 128),
    request_hash char(64) NOT NULL,
    state varchar(16) NOT NULL CHECK (state IN ('PROCESSING', 'COMPLETED')),
    response_status smallint,
    response_body jsonb,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    expires_at timestamptz NOT NULL,
    UNIQUE (student_id, idempotency_key),
    CHECK (state <> 'COMPLETED' OR (response_status IS NOT NULL AND response_body IS NOT NULL))
);
CREATE INDEX idempotency_expires_idx ON idempotency_record (expires_at);
