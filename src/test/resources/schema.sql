CREATE TYPE account_role AS ENUM ('STUDENT', 'ADMIN');
CREATE TYPE registration_status AS ENUM ('OPEN', 'CLOSED');
CREATE TYPE enrollment_status AS ENUM ('ENROLLED', 'FAILED');

CREATE TABLE account (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(20) NOT NULL UNIQUE,
    full_name varchar(100) NOT NULL,
    password_hash varchar(100) NOT NULL,
    role account_role NOT NULL
);

CREATE TABLE course (
    code varchar(12) PRIMARY KEY,
    name varchar(150) NOT NULL,
    credits smallint NOT NULL,
    prerequisite varchar(100),
    CONSTRAINT chk_course_credit_validity CHECK (credits > 0 AND credits < 10)
);

CREATE TABLE registration_period (
    term varchar(10) PRIMARY KEY,
    login_opens_at timestamptz NOT NULL,
    opens_at timestamptz NOT NULL,
    closes_at timestamptz NOT NULL,
    status registration_status NOT NULL,
    credit_limit smallint NOT NULL,
    CONSTRAINT chk_period_validity CHECK (login_opens_at <= opens_at AND opens_at < closes_at),
    CONSTRAINT chk_period_positive_limit CHECK (credit_limit > 0)
);

CREATE UNIQUE INDEX one_open_period
ON registration_period (status)
WHERE status = 'OPEN';

CREATE TABLE section (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_code varchar(12) NOT NULL REFERENCES course(code) ON DELETE CASCADE,
    term varchar(10) NOT NULL REFERENCES registration_period(term) ON DELETE CASCADE,
    lecturer varchar(100) NOT NULL,
    capacity smallint NOT NULL,
    enrolled_count smallint NOT NULL DEFAULT 0,
    session integer NOT NULL, -- bitmask 28 bit
    CONSTRAINT chk_section_positive_student_count CHECK (enrolled_count BETWEEN 0 AND capacity),
    CONSTRAINT chk_section_positive_capacity CHECK (capacity > 0),
    CONSTRAINT chk_section_session_validity CHECK (session > 0 AND session < 268435456)
);

CREATE INDEX idx_section_term_course
ON section (term, course_code);

CREATE TABLE enrollment (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id bigint NOT NULL REFERENCES account(id) ON DELETE CASCADE,
    section_id bigint NOT NULL REFERENCES section(id) ON DELETE CASCADE,
    status enrollment_status NOT NULL,
    fail_code varchar(30),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT chk_enrollment_status_validity CHECK (status <> 'FAILED' OR fail_code IS NOT NULL),
    CONSTRAINT uk_enrollment_student_section UNIQUE (student_id, section_id)
);

CREATE INDEX idx_enrollment_student_id ON enrollment (student_id);
CREATE INDEX idx_enrollment_section_id ON enrollment (section_id);

CREATE TABLE idempotency_record (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id bigint NOT NULL REFERENCES account(id) ON DELETE CASCADE,
    idempotency_key varchar(128) NOT NULL,
    request_hash char(64) NOT NULL,
    state varchar(16) NOT NULL,
    response_status smallint,
    response_body jsonb,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    expires_at timestamptz NOT NULL,
    CONSTRAINT chk_idempotency_key_state_validity CHECK (state IN ('PROCESSING', 'COMPLETED')),
    CONSTRAINT chk_idempotency_key_response_not_null_while_processing CHECK (state <> 'COMPLETED' OR (response_status IS NOT NULL AND response_body IS NOT NULL)),
    CONSTRAINT chk_idempotency_key_len_validity CHECK (length(idempotency_key) BETWEEN 1 AND 128)
);

CREATE UNIQUE INDEX uk_student_requests_idempotency ON idempotency_record (student_id, idempotency_key);
CREATE INDEX idx_idempotency_expires ON idempotency_record (expires_at);
